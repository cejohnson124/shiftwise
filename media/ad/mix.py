"""Builds music.wav from the Mixkit song "Sun and His Daughter" + the ad's sound effects,
and writes timing.js so the animation's key moments land on the song's real beats.

The animation is authored on a "design" clock (index.html). ANCHORS pin design times to
tracked beats in the song (song/beats.json, from song/beats.py); everything in between
is stretched linearly. Sound effects are placed with the same warp.
"""
import json, subprocess, wave
import numpy as np

SR = 44100
DUR = 30.0
import os
FFMPEG = os.path.abspath("node_modules/ffmpeg-static/ffmpeg.exe")

BEATS = json.load(open("song/beats.json"))
b = lambda k: BEATS[k]
# (design time in index.html, real time on the song's beat)
ANCHORS = [
    (0.0, 0.0),
    (0.5, b(1)),    # first whisper
    (2.5, b(4)),    # second whisper
    (5.0, b(9)),    # door opens
    (7.0, b(12)),   # "My sister's wedding."
    (8.0, b(14)),   # realization, push-in
    (9.0, b(15)),   # CUT: wedding (record scratch)
    (10.0, b(17)),  # "...Marcus?"
    (11.5, b(19)),  # "That'll be $18.50."
    (13.0, b(22)),  # "Conflicts get lost."
    (14.0, b(24)),  # "Weekends get ruined."
    (15.0, b(25)),  # CUT: phone
    (16.0, b(26)),  # whole-day toggle
    (18.0, b(30)),  # Submit
    (19.0, b(32)),  # CUT: manager + app
    (20.0, b(33)),  # Generate schedule
    (22.0, b(37)),  # flags
    (23.0, b(38)),  # Publish
    (24.5, b(41)),  # board hits the floor
    (25.0, b(42)),  # CUT: dance
    (27.0, b(45)),  # CUT: logo
    (29.0, b(48)),  # final hit
    (30.0, 30.0),
]
D = np.array([a for a, _ in ANCHORS]); Rt = np.array([r for _, r in ANCHORS])
W = lambda td: float(np.interp(td, D, Rt))  # design -> real

with open("timing.js", "w") as f:
    f.write("// generated by mix.py: design-time -> song-beat anchors, and tracked beats (s)\n")
    f.write("window.TIMING = " + json.dumps({"anchors": ANCHORS, "beats": [x for x in BEATS if x < 31]}) + ";\n")

# ------------------------------------------------------------------ song
raw = subprocess.run([FFMPEG, "-hide_banner", "-loglevel", "error", "-i", "song/song.mp3", "-t", str(DUR),
                      "-f", "s16le", "-ac", "2", "-ar", str(SR), "-"], capture_output=True, check=True).stdout
song = np.frombuffer(raw, dtype="<i2").astype(float).reshape(-1, 2) / 32768
N = int(SR * DUR)
song = np.pad(song, ((0, max(0, N - len(song))), (0, 0)))[:N]
g = np.ones(N)
def ramp(t0, t1, v0, v1):
    i0, i1 = int(t0 * SR), int(t1 * SR); g[i0:i1] = np.linspace(v0, v1, i1 - i0)
# record scratch: the song stops dead on the cut and drops back in one beat later
ramp(W(9.0) - 0.008, W(9.0), 1, 0); g[int(W(9.0) * SR):int(b(16) * SR)] = 0; ramp(b(16), b(16) + 0.01, 0, 1)
# ring out after the final hit
ramp(W(29.0) + 0.05, DUR, 1, 0)
song *= g[:, None] * 0.8

L = np.zeros(N); R = np.zeros(N)
rng = np.random.default_rng(7)
def add(t0, sig, gain=1.0, pan=0.0):
    i = int(round(t0 * SR))
    if i >= N: return
    sig = sig[:N - i]
    L[i:i + len(sig)] += sig * gain * np.cos((pan + 1) * np.pi / 4)
    R[i:i + len(sig)] += sig * gain * np.sin((pan + 1) * np.pi / 4)
tt = lambda d: np.arange(int(d * SR)) / SR
noise = lambda d: rng.uniform(-1, 1, int(d * SR))
def hp(x, a=0.85):
    y = np.zeros_like(x)
    for i in range(1, len(x)): y[i] = a * (y[i - 1] + x[i] - x[i - 1])
    return y
def env(d, a=0.005, r=0.02):
    e = np.ones(int(d * SR)); na, nr = int(a * SR), int(r * SR)
    if na: e[:na] = np.linspace(0, 1, na)
    if nr: e[-nr:] *= np.linspace(1, 0, nr)
    return e
def hz(n):
    names = {"C": 0, "D": 2, "E": 4, "F": 5, "G": 7, "A": 9, "B": 11}
    return 440 * 2 ** ((names[n[0]] + 12 * (int(n[-1]) + 1) - 69) / 12)
def tick(d=0.025): return hp(noise(d), 0.3) * np.exp(-tt(d) * 200)
def bell(f, d=1.0):
    t = tt(d)
    return (np.sin(2*np.pi*f*t)*np.exp(-t*4) + .5*np.sin(2*np.pi*f*2.76*t)*np.exp(-t*7)) * env(d, .001, .05)
def blip(f, d=0.09): t = tt(d); return np.sin(2*np.pi*f*t) * np.exp(-t*30) * env(d, .001, .01)

# fluorescent buzz (0-9) with gaps that match the light flicker in index.html
t = tt(W(9.0))
buzz = (np.sign(np.sin(2*np.pi*120*t))*.5 + np.sin(2*np.pi*240*t)) * .5
for a, c in [(0.75, 0.82), (2.1, 2.16), (2.22, 2.28), (6.4, 6.47)]:
    buzz[int(W(a)*SR):int(W(c)*SR)] = 0
e = np.ones(len(t)); e[:2205] = np.linspace(0, 1, 2205); e[-441:] *= np.linspace(1, 0, 441)
add(0, buzz * e, 0.02)
# record scratch
d = 0.38; t = tt(d); f = 900*np.exp(-t*6) + 160*np.sin(2*np.pi*9*t)**2
add(W(9.0), (np.sin(2*np.pi*np.cumsum(f)/SR)*.6 + hp(noise(d), .6)*.6) * np.exp(-t*5), 0.55)
# phone taps, typing, Submit ding
for td in (15.5, 16.0, 16.5): add(W(td), tick(), 0.3, 0.2)
for i in range(16): add(W(16.5 + i/16), tick(0.015), 0.14, 0.25)
for td in (18.0, 23.0):
    add(W(td), bell(hz("C6"), 1.2), 0.28, 0.1); add(W(td) + 0.06, bell(hz("G6"), 1.0), 0.16, -0.1)
# Generate click + one blip per schedule cell
add(W(20.0), tick(), 0.3)
penta = ["F5", "G5", "A5", "C6", "D6", "F6", "G6"]
for k in range(14): add(W(20 + k*0.125), blip(hz(penta[k % 7])), 0.11, -0.5 + k/13)
add(W(22.0), blip(hz("D5"), .15), .16); add(W(22.125), blip(hz("A4"), .15), .16)
add(W(23.0), tick(), 0.3)
# board hits the floor
t = tt(0.6); f = 70*np.exp(-t*6) + 35
add(W(24.5), np.sin(2*np.pi*np.cumsum(f)/SR)*np.exp(-t*8) + .3*hp(noise(.6), .4)*np.exp(-t*25), 0.8)

mix = song + np.stack([L, R], 1)
mix = np.tanh(mix * 1.1) / np.tanh(1.1) * 0.95
fade = int(0.05 * SR); mix[-fade:] *= np.linspace(1, 0, fade)[:, None]
with wave.open("music.wav", "wb") as w:
    w.setnchannels(2); w.setsampwidth(2); w.setframerate(SR)
    w.writeframes((np.clip(mix, -1, 1) * 32767).astype("<i2").tobytes())
print("wrote music.wav + timing.js")
for d_, r_ in ANCHORS: print(f"  design {d_:5.2f} -> {r_:6.3f}s")
